#!/usr/bin/env python3
"""Generate the gz world through_ring.sdf for the THROUGH mode (spec 13.2).

The ring is a static model made of `segments` cylinders along a circle. Its
plane normal points from the ring center towards `aim` (by default the hover
point 25 m above the start), so the initial dive goes roughly perpendicular
through the ring (tilted ring, option A).

All coordinates are gz world ENU [m]. Defaults reproduce the standard scene:

    ring center (25, 0, 10), inner diameter 2.0 m, tube diameter 0.15 m,
    24 segments, normal aimed at (0, 0, 25).

Spec 13.2 places the ring at (25, 0, 5) with a 20 m hover. Scene and hover were
both raised by 5 m (same 31 deg dive, same distance): with the ring at 5 m the
vehicle touched the ground after the ring (VERIFICATION.md 15.4, D8 = A).

The world origin is placed where the magnetic declination is ~0 (lat 47.398,
lon -4.67): gz-sim generates the field with the declination sign flipped,
which otherwise leaves the PX4 EKF heading off by about twice the local
declination (7 deg at the PX4 default location, VERIFICATION.md 14.1). The PX4
WMM table is 0 at lon -3.40; -4.67 also cancels the offset of the older gz
table (measured 0.85 deg heading error at -3.40).

Usage:
    gen_through_ring_world.py [-o Tools/simulation/gz/worlds/through_ring.sdf]
"""

import argparse
import math
import os

DEFAULT_OUTPUT = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    '../../Tools/simulation/gz/worlds/through_ring.sdf'))


def ring_orientation(center, aim):
    """Roll/pitch/yaw so that the model x axis (ring normal) points from center to aim."""
    dx, dy, dz = (aim[i] - center[i] for i in range(3))
    yaw = math.atan2(dy, dx)
    pitch = -math.atan2(dz, math.hypot(dx, dy))  # gz pitch: positive turns x downwards
    return 0.0, pitch, yaw


def ring_segments(inner_diameter, tube_diameter, segments):
    """Segment poses in the ring frame: ring in the y-z plane, normal along x."""
    r_tube = tube_diameter / 2.0
    r_center = inner_diameter / 2.0 + r_tube  # centerline radius of the tube
    # chord length plus a small overlap so the segments look closed
    length = 2.0 * r_center * math.sin(math.pi / segments) * 1.08
    poses = []
    for i in range(segments):
        phi = 2.0 * math.pi * i / segments
        # rotating the cylinder z axis by phi about x makes it tangent to the circle
        poses.append((0.0, r_center * math.cos(phi), r_center * math.sin(phi), phi, 0.0, 0.0))
    return poses, r_tube, length


def fmt(values):
    return ' '.join(f'{v:.6g}' for v in values)


def ring_model_sdf(args):
    roll, pitch, yaw = ring_orientation(args.center, args.aim)
    poses, radius, length = ring_segments(args.inner_diameter, args.tube_diameter, args.segments)
    material = """
          <material>
            <ambient>1 0 0 1</ambient>
            <diffuse>1 0 0 1</diffuse>
            <specular>0 0 0 1</specular>
            <emissive>1 0 0 1</emissive>
          </material>"""
    parts = []
    for i, pose in enumerate(poses):
        geometry = f"""
          <geometry>
            <cylinder>
              <radius>{radius:.6g}</radius>
              <length>{length:.6g}</length>
            </cylinder>
          </geometry>"""
        parts.append(f"""
        <collision name="segment_{i}_collision">
          <pose>{fmt(pose)}</pose>{geometry}
        </collision>
        <visual name="segment_{i}_visual">
          <pose>{fmt(pose)}</pose>{geometry}{material}
          <cast_shadows>false</cast_shadows>
        </visual>""")
    return f"""
    <!-- inner diameter {args.inner_diameter} m, tube diameter {args.tube_diameter} m,
         normal (model x axis) aimed at {fmt(args.aim)} -->
    <model name="through_ring">
      <static>true</static>
      <pose>{fmt(args.center)} {fmt((roll, pitch, yaw))}</pose>
      <link name="link">{''.join(parts)}
      </link>
    </model>"""


def world_sdf(args):
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by Tools/through/gen_through_ring_world.py, do not edit by hand. -->
<sdf version="1.9">
  <world name="through_ring">
    <physics type="ode">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>250</real_time_update_rate>
    </physics>
    <gravity>0 0 -9.8</gravity>
    <magnetic_field>6e-06 2.3e-05 -4.2e-05</magnetic_field>
    <atmosphere type="adiabatic"/>
    <scene>
      <grid>false</grid>
      <ambient>0.5 0.5 0.5 1</ambient>
      <!-- plain sky: no <sky> element, uniform background color -->
      <background>0.62 0.76 0.90 1</background>
      <shadows>false</shadows>
    </scene>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry>
            <plane>
              <normal>0 0 1</normal>
              <size>1 1</size>
            </plane>
          </geometry>
        </collision>
        <visual name="visual">
          <geometry>
            <plane>
              <normal>0 0 1</normal>
              <size>500 500</size>
            </plane>
          </geometry>
          <material>
            <ambient>0.45 0.50 0.42 1</ambient>
            <diffuse>0.45 0.50 0.42 1</diffuse>
            <specular>0.1 0.1 0.1 1</specular>
          </material>
        </visual>
      </link>
    </model>
    <light name="sunUTC" type="directional">
      <pose>0 0 500 0 0 0</pose>
      <cast_shadows>false</cast_shadows>
      <intensity>1</intensity>
      <direction>0.001 0.625 -0.78</direction>
      <diffuse>0.904 0.904 0.904 1</diffuse>
      <specular>0.271 0.271 0.271 1</specular>
      <attenuation>
        <range>2000</range>
        <linear>0</linear>
        <constant>1</constant>
        <quadratic>0</quadratic>
      </attenuation>
    </light>{ring_model_sdf(args)}
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{args.lat:.9f}</latitude_deg>
      <longitude_deg>{args.lon:.9f}</longitude_deg>
      <elevation>0</elevation>
    </spherical_coordinates>
  </world>
</sdf>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('-o', '--output', default=DEFAULT_OUTPUT)
    parser.add_argument('--center', type=float, nargs=3, default=[25.0, 0.0, 10.0], metavar=('X', 'Y', 'Z'))
    parser.add_argument('--aim', type=float, nargs=3, default=[0.0, 0.0, 25.0], metavar=('X', 'Y', 'Z'),
                        help='point the ring normal is aimed at')
    parser.add_argument('--inner-diameter', type=float, default=2.0)
    parser.add_argument('--tube-diameter', type=float, default=0.15)
    parser.add_argument('--segments', type=int, default=24)
    parser.add_argument('--lat', type=float, default=47.397971, help='world origin latitude [deg]')
    parser.add_argument('--lon', type=float, default=-4.67,
                        help='world origin longitude [deg] (default: magnetic declination ~0)')
    args = parser.parse_args()

    with open(args.output, 'w') as f:
        f.write(world_sdf(args))
    print(f'wrote {args.output}')


if __name__ == '__main__':
    main()
